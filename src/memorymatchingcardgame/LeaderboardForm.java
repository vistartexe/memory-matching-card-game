    private void loadLeaderboard() {
        tableModel.setRowCount(0);

        String filter = (String) comboxFilter.getSelectedItem();

        try {

            List<LeaderboardEntry> entries = playHistoryDAO.getTopScores(filter);

            for (LeaderboardEntry entry
                    : entries) {

                tableModel.addRow(
                        new Object[]{
                            entry.getRank(),
                            entry.getUsername(),
                            entry.getScore(),
                            formatDuration(
                                    entry.getDurationSeconds()
                            ),
                            entry.getDifficulty(),
                            entry.getPlayedAt()
                        }
                );
            }

            if (entries.isEmpty()) {

                JOptionPane.showMessageDialog(
                        this,
                        "No available score data yet.",
                        "Info",
                        JOptionPane.INFORMATION_MESSAGE
                );
            }

        } catch (SQLException ex) {

            JOptionPane.showMessageDialog(
                    this,
                    "Leaderboard loading has failed: "
                    + ex.getMessage(),
                    "Database Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }
    
    private String formatDuration(int seconds) {
        int minutes = seconds / 60;
        int secs = seconds % 60;

        return String.format(
                "%02d:%02d",
                minutes,
                secs
        );
    }
   
